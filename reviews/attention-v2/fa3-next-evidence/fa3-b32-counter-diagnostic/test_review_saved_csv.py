"""Reviewer regression against the already captured installed NCU CSV format."""
import hashlib
import importlib.util
from pathlib import Path
import unittest

HERE = Path(__file__).resolve().parent
spec = importlib.util.spec_from_file_location('review_csv_helpers', HERE/'csv_helpers.py')
reader = importlib.util.module_from_spec(spec)
spec.loader.exec_module(reader)


class SavedInstalledCsvTests(unittest.TestCase):
    def test_parser_reads_actual_successful_installed_ncu_output(self):
        path = HERE.parent/'eager-counter-repair/3-stdout.txt'
        raw = path.read_bytes()
        # Source fixture is the preserved real tiny-kernel profiler output,
        # not a fabricated table generated by this parser's implementation.
        self.assertEqual(len(raw), 13518)
        self.assertEqual(hashlib.sha256(raw).hexdigest(),
            '176beb19e4618b1c52f6ba737ceaf0d6f5353ea8574a823276530a667763ebef')
        parsed = reader.parse_ncu_csv(raw.decode(), ['sm__cycles_elapsed.avg'])
        self.assertEqual(parsed['row_count'], 1)
        self.assertEqual(parsed['kernel_name'], 'okc_counter_gate')
        self.assertEqual(parsed['grid'], [1, 1, 1])
        self.assertEqual(parsed['block'], [128, 1, 1])
        self.assertEqual(parsed['metrics']['sm__cycles_elapsed.avg']['unit'], 'cycle')
        self.assertEqual(parsed['metrics']['sm__cycles_elapsed.avg']['value'], 5541.35)


if __name__ == '__main__':
    unittest.main()
